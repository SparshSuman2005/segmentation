import torch


# ============================================================
# SEGMENTATION METRICS
# ============================================================

def calculate_metrics(
    predictions,
    masks
):


    # --------------------------------------------------------
    # Convert logits to probabilities
    # --------------------------------------------------------

    predictions = torch.sigmoid(
        predictions
    )


    # --------------------------------------------------------
    # Convert probabilities to binary mask
    # --------------------------------------------------------

    predictions = (
        predictions > 0.5
    ).float()


    masks = (
        masks > 0.5
    ).float()


    # --------------------------------------------------------
    # Flatten
    # --------------------------------------------------------

    predictions = predictions.view(-1)

    masks = masks.view(-1)


    # --------------------------------------------------------
    # True Positive
    # --------------------------------------------------------

    TP = (
        (predictions == 1) &
        (masks == 1)
    ).sum().float()


    # --------------------------------------------------------
    # False Positive
    # --------------------------------------------------------

    FP = (
        (predictions == 1) &
        (masks == 0)
    ).sum().float()


    # --------------------------------------------------------
    # False Negative
    # --------------------------------------------------------

    FN = (
        (predictions == 0) &
        (masks == 1)
    ).sum().float()


    # --------------------------------------------------------
    # IoU
    # --------------------------------------------------------

    iou = TP / (
        TP + FP + FN + 1e-8
    )


    # --------------------------------------------------------
    # Dice
    # --------------------------------------------------------

    dice = (
        2 * TP
    ) / (
        2 * TP + FP + FN + 1e-8
    )


    # --------------------------------------------------------
    # Precision
    # --------------------------------------------------------

    precision = TP / (
        TP + FP + 1e-8
    )


    # --------------------------------------------------------
    # Recall
    # --------------------------------------------------------

    recall = TP / (
        TP + FN + 1e-8
    )


    # --------------------------------------------------------
    # F1 Score
    # --------------------------------------------------------

    f1 = (
        2 * precision * recall
    ) / (
        precision + recall + 1e-8
    )


    return {

        "iou": iou.item(),

        "dice": dice.item(),

        "precision": precision.item(),

        "recall": recall.item(),

        "f1": f1.item()

    }